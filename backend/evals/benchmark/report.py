from collections.abc import Iterable, Mapping, Sequence

from evals.benchmark.models import BenchmarkResult, ItemScore, LemmaScore
from evals.gold import Tag

TAG_ORDER = (Tag.PLAIN, Tag.CLITIC, Tag.ARTICLE, Tag.MUTATION, Tag.INFLECTION)


def render_report(
    result: BenchmarkResult, *, recommendation: str, environment: Mapping[str, str]
) -> str:
    """The benchmark as a Markdown report."""
    sections = (
        "# Lemmatiser benchmark",
        _introduction(result, environment),
        _summary(result),
        _lemma_level(result),
        _item_level(result),
        _authoring(result),
        _runtime(result),
        "## Recommendation\n\n" + recommendation.strip(),
        _notes(),
    )

    return "\n\n".join(sections) + "\n"


def _introduction(result: BenchmarkResult, environment: Mapping[str, str]) -> str:
    versions = ", ".join(f"{name} {version}" for name, version in environment.items())

    return (
        f"Scored on the {result.sentences} gold sentences "
        f"({result.tokens} tokens) in `backend/evals/gold/sentences.yaml`. "
        f"Generated by `poe benchmark` ({versions}). "
        "Runtimes depend on the machine."
    )


def _summary(result: BenchmarkResult) -> str:
    overall = result.declared_forms_only.overall
    rows = [
        ["Declared forms only", "-", "-", *_item_cells(overall), "-", "-", "-"],
        *(
            [
                row.name,
                _percent(row.lemmas.overall.accuracy),
                f"{row.lemmas.overall.average_candidates:.2f}",
                *_item_cells(row.items.overall),
                f"{row.authoring.surfaced}/{row.authoring.undeclared}",
                _percent(row.authoring.precision),
                f"{row.milliseconds_per_sentence:.2f}",
            ]
            for row in result.lemmatisers
        ),
    ]

    return "## Summary\n\n" + _table(
        (
            "",
            "Lemma accuracy",
            "Avg candidates",
            "Item precision",
            "Item recall",
            "Item F1",
            "Forms surfaced",
            "Suggestion precision",
            "ms/sentence",
        ),
        rows,
    )


def _lemma_level(result: BenchmarkResult) -> str:
    return (
        "## Lemma level\n\n"
        "Accuracy is how often the gold lemma is among a token's candidates. "
        "The second number is the average candidates per token. "
        "Each tag covers the tokens of the sentences carrying it.\n\n"
        + _table(
            ("", "All", *(tag.value for tag in TAG_ORDER)),
            [
                [
                    row.name,
                    _lemma_cell(row.lemmas.overall),
                    *(_lemma_cell(row.lemmas.by_tag[tag]) for tag in TAG_ORDER),
                ]
                for row in result.lemmatisers
            ],
        )
    )


def _item_level(result: BenchmarkResult) -> str:
    rows = [
        [
            "Declared forms only",
            *_item_row(
                result.declared_forms_only.overall, result.declared_forms_only.by_tag
            ),
        ],
        *(
            [row.name, *_item_row(row.items.overall, row.items.by_tag)]
            for row in result.lemmatisers
        ),
    ]

    return (
        "## Item level\n\n"
        "Precision / recall of `detect_items` against the gold patterns and lexemes. "
        "For each lemmatiser, every token also matches the lexemes its candidate "
        "lemmas point to.\n\n"
        + _table(("", "All", *(tag.value for tag in TAG_ORDER)), rows)
    )


def _authoring(result: BenchmarkResult) -> str:
    rows = [
        [
            row.name,
            str(row.authoring.undeclared),
            f"{row.authoring.surfaced} ({_percent(row.authoring.recall)})",
            str(row.authoring.suggestions),
            f"{row.authoring.correct_suggestions} ({_percent(row.authoring.precision)})",
        ]
        for row in result.lemmatisers
    ]
    missed = _bullets((row.name, row.authoring.missed) for row in result.lemmatisers)
    wrong = _bullets((row.name, row.authoring.wrong) for row in result.lemmatisers)

    return (
        "## Authoring aid\n\n"
        "Gold tokens that are a form of a single-word lexeme the curriculum "
        "doesn't recognise yet, and how many each lemmatiser maps to the right "
        "lexeme. A suggestion is any new token-to-lexeme link it proposes, "
        "right or wrong.\n\n"
        + _table(
            ("", "Undeclared forms", "Surfaced", "Suggestions", "Correct suggestions"),
            rows,
        )
        + "\n\nMissed forms:\n\n"
        + missed
        + "\n\nWrong suggestions:\n\n"
        + wrong
    )


def _runtime(result: BenchmarkResult) -> str:
    return (
        "## Runtime\n\nBest of several passes over all sentences, after a warm-up pass. Model loading is excluded.\n\n"
        + _table(
            ("", "ms/sentence"),
            [
                [row.name, f"{row.milliseconds_per_sentence:.2f}"]
                for row in result.lemmatisers
            ],
        )
    )


def _notes() -> str:
    return (
        "## Notes\n\n"
        "- The gold lemmas and annotations are hand-written and unreviewed by a "
        "fluent speaker, so small differences are not meaningful.\n"
        "- Inflected forms the curriculum doesn't declare (`gwelais`) still "
        "expect their lexeme in the gold set, so declared forms only misses them by design.\n"
        "- The stray pronoun `i` is detected as the preposition `lex:i` by every "
        "row, so it costs precision everywhere.\n"
        "- Lemmas are matched ignoring case. A lemmatiser is credited when the "
        "gold lemma is among its candidates, so more candidates can only help "
        "accuracy. Compare the average number of candidates alongside it."
    )


def _bullets(entries: Iterable[tuple[str, Sequence[str]]]) -> str:
    return "\n".join(
        f"- {name}: {', '.join(values) or 'none'}" for name, values in entries
    )


def _item_cells(score: ItemScore) -> list[str]:
    return [_percent(score.precision), _percent(score.recall), _percent(score.f1)]


def _item_row(overall: ItemScore, by_tag: Mapping[Tag, ItemScore]) -> list[str]:
    return [
        _item_pair(overall),
        *(_item_pair(by_tag[tag]) for tag in TAG_ORDER),
    ]


def _item_pair(score: ItemScore) -> str:
    return f"{_percent(score.precision)} / {_percent(score.recall)}"


def _lemma_cell(score: LemmaScore) -> str:
    return f"{_percent(score.accuracy)} ({score.average_candidates:.1f})"


def _percent(value: float) -> str:
    return f"{value * 100:.1f}%"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]

    return "\n".join(lines)
